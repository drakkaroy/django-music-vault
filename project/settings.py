"""Settings for the standalone django-music-vault project.

Everything configurable comes from environment variables (a ``.env``
file at the repo root is loaded if present). With no configuration at
all it runs on SQLite so ``migrate`` + ``runserver`` work out of the box;
set DB_ENGINE=postgresql to use Postgres (e.g. the Collector App DB).
"""

import os
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent


def _load_env(path):
    """Minimal .env loader (KEY=VALUE lines, # comments) — no extra deps."""
    if not path.exists():
        return
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        os.environ.setdefault(key.strip(), value.strip())


